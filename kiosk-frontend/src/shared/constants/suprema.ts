/**
 * 슈프리마 타임아웃 사다리.
 *
 * `START` 는 두 홉을 거친다: 프론트 → 백엔드 → 서브프로세스. **바깥 홉이 항상 안쪽보다
 * 길어야** 안쪽이 결론을 내기 전에 바깥이 먼저 포기하는 일이 없다. 두 값이 같으면 어느
 * 쪽이 먼저 끝날지 모르는 경합이 되고, 그때는 스캔이 실패했는지 프론트가 못 기다린
 * 건지 구분할 수 없다.
 *
 * 대기 시간은 프론트가 **명시적으로 실어 보낸다** — 생략하면 백엔드 기본값(60초)에
 * 의존하게 되어, 그 기본값이 바뀌는 순간 사다리가 조용히 뒤집힌다.
 */

/** 문서를 올릴 때까지 기다리는 시간. 백엔드가 이 값으로 서브프로세스를 감싼다(안쪽). */
export const SUPREMA_SCAN_TIMEOUT_MS = 60_000;

/** 프론트 트랜스포트(바깥). 안쪽 + 여유 — 백엔드의 실패 응답을 받을 수 있어야 한다. */
export const SUPREMA_SCAN_TRANSPORT_TIMEOUT_MS =
  SUPREMA_SCAN_TIMEOUT_MS + 10_000;

/** `PING` 은 캐시된 상태를 되돌려줄 뿐이라 짧게. 콜드 스폰 한 번은 감당할 정도. */
export const SUPREMA_PING_TIMEOUT_MS = 15_000;
