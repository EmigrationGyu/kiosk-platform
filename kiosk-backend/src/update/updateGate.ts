/**
 * 교체가 확정된 뒤로는 새 요청을 받지 않는다.
 *
 * 정숙 대기만으로는 "그 순간 조용했다"까지만 보장한다 — 확인과 실제 교체 사이에 시작된 명령은 결과
 * 불명이 되고, 현금 방출 같은 건 되돌릴 수 없다. 잠그고 나면 정숙이 표본이 아니라 **래치**가 된다.
 *
 * 장치 명령만이 아니라 **전부** 막는 이유: 거절은 실행 **전에** 일어나 "확실히 아무 일도 없었다"가
 * 보장되므로 소비처가 조용히 재시도하면 그만이다 — 예외를 파면 빠뜨린 경로가 곧 구멍이 된다.
 *
 * 상한을 두지 않는다. "부모는 멀쩡한데 적용만 영영 안 일어나는" 상태는 존재하지 않는다(자식은 부모와
 * 함께 죽는다). 대신 부모가 **백엔드를 살려두기로 했을 때 응답으로 풀어준다**.
 */
let locked = false;

export const updateGate = {
  lock(): void {
    locked = true;
  },
  unlock(): void {
    locked = false;
  },
  isLocked(): boolean {
    return locked;
  },
};
